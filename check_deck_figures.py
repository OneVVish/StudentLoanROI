def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--self-test", action="store_true",
                    help="run the negative controls; needs no decks")
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="say which scenario is running")
    a = ap.parse_args()

    if a.self_test:
        return self_test()

    missing = [n for n in DECKS.values() if not (PRESENTATION / n).exists()]
    if missing:
        print("check_deck_figures: SKIPPED. presentation/ is gitignored, so "
              "the decks are not in this tree.")
        print(f"  not found: {', '.join(missing)}")
        return 0

    print("check_deck_figures: loading app.py's model layer")
    ns = load_model()
    checks = build_checks(ns, verbose=a.verbose)
    problems = run(read_decks(), checks)

    if problems:
        print(f"\nFAILED: {len(problems)} problem(s)\n")
        for p in problems:
            print(f"  {p}")
        return 1
    print(f"OK: {len(checks)} figures reproduce across {len(DECKS)} surfaces, "
          f"and every money figure, count and percentage on them is accounted "
          f"for.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
