# ---------------------------------------------------------------- renderings

def money_forms(v: float) -> list:
    """Every way a deck may legitimately write one derived money figure.

    All four are computed from `v`; none is typed. The k and M forms exist
    because the decks write "$42k behind" and "$2.0M ahead" where the full
    figure would not fit a stat band.
    """
    v = float(v)
    sign = "-" if v < 0 else ""
    a = abs(v)
    out = [f"{sign}${a:,.0f}",
           f"{sign}${round(a, -2):,.0f}",
           f"{sign}${round(a, -3):,.0f}"]
    if a >= 1_000:
        out.append(f"{sign}${round(a / 1_000):,.0f}k")
    if a >= 100_000:
        out.append(f"{sign}${a / 1_000_000:.1f}M")
    # A premium is written with its sign on the deck ("+$581,000"); a break-even
    # never is. Offer both so one check covers the column it appears in.
    if v > 0:
        out += ["+" + s for s in list(out)]
    if v < 0:
        # A deck may put the direction in words instead of in a sign:
        # "Podiatry: $42k behind a high school grad". Accepting the unsigned
        # magnitude is what lets one check cover both conventions, and it is
        # why this guard cannot catch a SIGN error. It is aimed at a figure
        # from a different model era, which is wrong by tens of percent.
        out += [s.lstrip("-") for s in list(out)]
    return sorted(set(out))


def count_forms(n: int) -> list:
    return sorted({f"{int(n):,}", str(int(n))})


def pct_forms(x: float) -> list:
    """A share written as the deck writes it: whole percent, or one decimal."""
    return sorted({f"{round(x * 100):.0f}%", f"{x * 100:.1f}%"})


# ------------------------------------------------------------------ the deck

TOKEN = re.compile(r"\$\s*-?[\d,]+(?:\.\d+)?\s*[kKmM]?\b"
                   r"|\b\d{1,3}(?:,\d{3})+\b"
                   r"|\b\d+(?:\.\d+)?%")
HEADLINE = re.compile(r'<div class="(?:stat-num|big-number)">(.*?)</div>', re.S)


def visible(raw: str) -> str:
    """The deck's reader-facing text, normalised so one spelling matches.

    Strips style, script and comments first: the stylesheet is full of numbers
    (`0.85em`, `#1a56db`) and none of them is a claim about anything.
    """
    t = re.sub(r"(?is)<(style|script)\b.*?</\1>", " ", raw)
    t = re.sub(r"(?s)<!--.*?-->", " ", t)
    t = re.sub(r"<[^>]+>", " ", t)
    t = html_mod.unescape(t)
    # &minus;, en dash and em dash all arrive as a sign in front of money.
    t = t.replace("−", "-").replace("–", "-").replace("—", "-")
    t = t.replace("\xa0", " ")
    # "- $35,400" and "-$35,400" are the same claim.
    t = re.sub(r"-\s+\$", "-$", t)
    return re.sub(r"\s+", " ", t)


def deck_tokens(raw: str) -> set:
    """Everything on this deck that must be accounted for."""
    toks = set(TOKEN.findall(visible(raw)))
    for m in HEADLINE.finditer(raw):
        cell = visible(m.group(1))
        toks |= set(TOKEN.findall(cell))
        # A headline that is a bare count ("836", "50") carries no separator and
        # would escape the sweep, and those are the figures a deck is read for.
        if re.fullmatch(r"\d+", cell.strip()):
            toks.add(cell.strip())
    return {t.replace(" ", "") for t in toks}


# ------------------------------------------------------------- the model layer

def load_model():
    """app.py's sections 1 and 2, the way analyze_model.py loads them."""
    src = (REPO / "app.py").read_text()
    m = re.search(r"^# =+\n# 3\. PAGE CONFIG & SESSION STATE", src, re.M)
    if not m:
        sys.exit("check_deck_figures: app.py's section 3 banner moved; this "
                 "script execs everything above it as the model layer.")
    ns = {"__name__": "deck_figure_guard", "__file__": str(REPO / "app.py")}
    exec(compile(src[:m.start()], str(REPO / "app.py"), "exec"), ns)
    return ns


def premium(ns, major_data, title, *, years=10, loan=0.0, idx=1.0, col=100.0,
            oop=0.0):
    """The earnings premium the app would show, for one occupation.

    `enrollment_years` is pre_earnings_years, not program_years: for an
    occupation with a training overlay the earnings curve starts at the
    bachelor's and the baseline must start there too (CLAUDE.md, "Both sides of
    the ROI comparison must agree what year 0 is"). Passing program_years here
    reported a podiatrist as $237,093 behind at ten years against a true
    $41,713, which is the shape of error this whole guard exists to catch.
    """
    saved = ns.get("MAJOR_DATA")
    ns["MAJOR_DATA"] = major_data
    try:
        pyrs = ns["program_years_for_major"](title)
        enr = ns["pre_earnings_years"](title, pyrs)
        r = ns["compute_scenario_results"](
            major_name=title, loan_amount=loan, interest_rate=RATE,
            repayment_strategy=STRATEGY, personal_contribution=oop,
            col_index=col, roi_window_years=years, hs_wage_index=idx,
            enrollment_years=enr, working_years=0,
            baseline_start_age=ns["baseline_start_age_for"](pyrs, enr, title),
            include_fees=True)
        return r
    finally:
        ns["MAJOR_DATA"] = saved


def breakeven(ns, major_data, title):
    saved = ns.get("MAJOR_DATA")
    ns["MAJOR_DATA"] = major_data
    try:
        pyrs = ns["program_years_for_major"](title)
        enr = ns["pre_earnings_years"](title, pyrs)
        out = ns["find_breakeven_loan"](
            title, RATE, STRATEGY, col_index=100.0, roi_window_years=10,
            hs_wage_index=1.0, enrollment_years=enr, working_years=0,
            baseline_start_age=ns["baseline_start_age_for"](pyrs, enr, title),
            include_fees=True)
        return out.get("breakeven_loan")
    finally:
        ns["MAJOR_DATA"] = saved


# ------------------------------------------------------------------ the checks

def build_checks(ns, verbose=False):
    """(label, forms, files) triples. `forms` is what the deck may say."""
    import pandas as pd

    checks = []

    def add(label, files, forms):
        checks.append((label, tuple(files), tuple(forms)))

    say = (lambda s: print(f"    {s}")) if verbose else (lambda s: None)

    # --- committed datasets, no model run -------------------------------
    coa = pd.read_csv(REPO / "data" / "college_coa_clean.csv")
    career = ns["build_major_data"](ns["CAREERS_CSV_PATH_NATIONAL"],
                                    mode=ns["DATASET_MODE_CAREER"])
    major = ns["build_major_data"](ns["CAREERS_CSV_PATH_NATIONAL"],
                                   mode=ns["DATASET_MODE_MAJOR"])
    cc = pd.read_csv(REPO / "data" / "cc_costs_clean.csv")
    gd = pd.read_csv(REPO / "data" / "graduate_debt_clean.csv")

    add("colleges in the cost file", EVERYWHERE, count_forms(len(coa)))
    add("careers in Career mode", EVERYWHERE, count_forms(len(career)))
    add("majors in Major mode", EVERYWHERE, count_forms(len(major)))
    add("career + major paths", DECK_ONLY, count_forms(len(career) + len(major)))
    add("cities", DECK_ONLY, count_forms(len(ns["CITY_DATA"])))
    # Graduate and professional schools publishing a debt median: everything in
    # the field-of-study file that is not a bachelor's row.
    add("graduate and professional schools", DECK_ONLY,
        count_forms(gd[gd["credential"] != "bachelor"]["UNITID"].nunique()))

    states = {s for s in cc["state"] if s in ns["US_STATES"]}
    add("states with a community-college price", DECK_ONLY, count_forms(len(states)))

    med = float(cc["in_district"].median())
    add("national median in-district tuition", ("cc", "cc_handout"), money_forms(med))
    add("two years of it", ("cc",), money_forms(med * 2))
    ca = float(cc.loc[cc["state"] == "CA", "in_district"].iloc[0])
    add("California in-district tuition", ("cc",), money_forms(ca))
    add("two years of California", ("cc",), money_forms(ca * 2))

    assoc_cols = (coa["programs_assoc"].fillna("").astype(str).str.strip() != "").sum()
    add("colleges awarding an associate's", ("cc",), count_forms(assoc_cols))

    # The residency gap, the three figures the school-search caption quotes.
    gap = coa[coa["in_state_coa"].notna() & coa["out_of_state_coa"].notna()
              & (coa["out_of_state_coa"] > coa["in_state_coa"])]
    add("share of colleges charging more out of state", ("hs",),
        pct_forms(len(gap) / len(coa)))
    per_year = float((gap["out_of_state_coa"] - gap["in_state_coa"]).median())
    add("median out-of-state gap a year", ("hs",), money_forms(per_year))
    add("that gap over four years", ("hs",), money_forms(per_year * 4))

    # --- federal borrowing constants ------------------------------------
    add("Parent PLUS aggregate limit", EVERYWHERE,
        money_forms(ns["PARENT_PLUS_AGGREGATE_LIMIT"]))
    add("Parent PLUS annual limit", EVERYWHERE,
        money_forms(ns["PARENT_PLUS_ANNUAL_LIMIT"]))
    add("dependent first-year Direct limit", EVERYWHERE,
        money_forms(ns["FEDERAL_DIRECT_ANNUAL_LIMITS"]["dependent"][1]))

    # --- Los Angeles, the slide the audit found three eras on ------------
    la = ns["build_major_data"](ns["CAREERS_CSV_PATH_NATIONAL"],
                                mode=ns["DATASET_MODE_CAREER"], city=CITY_LA)
    idx = ns["get_baseline_wage_index"](CITY_LA)
    col = ns["CITY_DATA"][CITY_LA]["col_index"]
    add("LA high school baseline", ("cc",),
        money_forms(ns["HS_GRAD_SALARY"] * idx))

    rad = "Radiologic Technologists and Technicians"
    add("LA radiologic technologist entry pay", ("cc",),
        money_forms(la[rad]["starting_salary"]))
    say("running the LA radiologic scenario")
    r = premium(ns, la, rad, idx=idx, col=col, oop=ca * 2)
    add("LA radiologic ten-year gain", ("cc",),
        money_forms(r["roi_result"]["earnings_premium"]))

    assoc = [t for t, e in la.items()
             if e.get("typical_education") == "Associate's degree"]
    add("associate's careers", ("cc",), count_forms(len(assoc)))
    say(f"sweeping {len(assoc)} LA associate's careers")
    below = sum(1 for t in assoc
                if premium(ns, la, t, idx=idx, col=col)["roi_result"]
                ["earnings_premium"] < 0)
    add("LA associate's careers below the baseline", ("cc",),
        count_forms(below))

    no_degree = [t for t, e in career.items()
                 if e.get("typical_education") in
                 ("High school diploma or equivalent",
                  "No formal educational credential")]
    add("careers needing no degree", ("cc",), count_forms(len(no_degree)))

    # --- the two result slides ------------------------------------------
    # WHICH SURFACE CARRIES WHICH FIGURE IS NOT UNIFORM, and assuming it was
    # produced four false failures on this guard's first run. The community
    # college DECK has no break-even column (its last column is the crossover
    # age) while both handouts do, and the same deck never states the monthly
    # payment. A row is therefore scoped per figure, not per row.
    HS_SIDE = ("hs", "hs_handout")
    CC_SIDE = ("cc", "cc_handout")
    ROWS = {
        # title: (files carrying pay and premium, files carrying the break-even)
        "Software Developers": (HS_SIDE, HS_SIDE),
        "Registered Nurses": (HS_SIDE, HS_SIDE),
        "Kindergarten Teachers, Except Special Education":
            (HS_SIDE + CC_SIDE, ("hs", "hs_handout", "cc_handout")),
        "Dental Hygienists": (CC_SIDE, ("cc_handout",)),
        "Respiratory Therapists": (CC_SIDE, ("cc_handout",)),
    }
    for title, (shown, be_files) in ROWS.items():
        say(f"running {title}")
        r = premium(ns, career, title, loan=LOAN)
        add(f"{title}: starting pay", shown,
            money_forms(career[title]["starting_salary"]))
        add(f"{title}: ten-year premium", shown,
            money_forms(r["roi_result"]["earnings_premium"]))
        add(f"{title}: debt it can carry", be_files,
            money_forms(breakeven(ns, career, title)))
        if title == "Software Developers":
            add("the monthly payment every row shares",
                ("hs",) + HANDOUTS,
                money_forms(r["repayment_result"]["monthly_payment"]))

    # --- the findings slide ---------------------------------------------
    say("running Podiatrists at 10 and 30 years")
    add("podiatry, behind at ten years", ("hs",),
        money_forms(premium(ns, career, "Podiatrists", years=10)
                    ["roi_result"]["earnings_premium"]))
    add("podiatry, ahead at thirty", ("hs",),
        money_forms(premium(ns, career, "Podiatrists", years=30)
                    ["roi_result"]["earnings_premium"]))

    bach = [t for t, e in career.items()
            if e.get("typical_education") == "Bachelor's degree"]
    say(f"sweeping {len(bach)} bachelor's careers at zero debt")
    fail = sum(1 for t in bach
               if premium(ns, career, t)["roi_result"]["earnings_premium"] < 0)
    add("bachelor's careers behind at ten years, no debt", ("hs",),
        pct_forms(fail / len(bach)))

    # --- the school searches --------------------------------------------
    say("running the two school searches")
    ns["MAJOR_DATA"] = career
    fam = next(k for k, v in ns["CIP_FAMILY_TITLES"].items()
               if v == "Computer & Information Sciences")
    hs_hits = ns["search_schools_by_budget"](fam, "Bachelor's degree", 25_000,
                                             home_state=None, limit=100_000)
    add("colleges teaching CS under the budget", ("hs",),
        count_forms(len(hs_hits)))
    add("states they sit in", ("hs",), count_forms(hs_hits["STABBR"].nunique()))
    cc_hits = ns["search_schools_by_budget"](fam, "Associate's degree", 15_000,
                                             home_state="CA", limit=100_000)
    add("colleges teaching the associate's under the budget", ("cc",),
        count_forms(len(cc_hits)))
    add("states they sit in (associate's)", ("cc",),
        count_forms(cc_hits["STABBR"].nunique()))
    add("of them in California", ("cc",),
        count_forms((cc_hits["STABBR"] == "CA").sum()))

    return checks


