#!/usr/bin/env python3
"""Every model-dependent figure on the counselor decks still reproduces.

    python3 check_deck_figures.py
    python3 check_deck_figures.py --self-test    # the negative controls, no decks needed

WHY THIS EXISTS. `presentation/` is gitignored, so the two decks and the two
handouts had no guard at all while every other published surface here has one:
the book has check_book_figures, the infographics have check_chart_basis and
check_chart_prose, the app has eleven. An audit on 2026-09-23 found deck figures
from THREE different model eras sitting beside each other:

  $56,626   an LA high school baseline scaled by the ALL-OCCUPATIONS metro index,
            which the model stopped using on 2026-09-22
  $174k     a ten-year gain computed before the 2026-08-18 real-units baseline
            correction; the same scenario now reads about $406,000
  "13 of 48" the same era, now 3 of 48
  $1,390    California community-college tuition from the NCES dict, superseded
  $3,890    by the IPEDS CSV the app actually reads on 2026-08-20

A deck figure has no denominator, no reader who can check it and, until now,
nothing that recomputes it. The $3,890 case is the sharpest: it is STILL a live
constant in app.py (COMMUNITY_COLLEGE_COA_DEFAULT, the CSV-absent fallback), so
grepping the repo CONFIRMS the stale number. Only re-deriving finds it.

WHAT IT DOES. Two halves, and the second is the one that cannot quietly narrow:

  1. FIGURES. Each check derives a value from app.py's own model or from a
     committed dataset, renders it the ways a deck may legitimately write it,
     and asserts one of those renderings is on the named deck. The expectation
     is never read off the decks, which is the rule this repo states everywhere
     (`check_chart_axes`, the residency guard): a check that derives its
     expectation from the thing under test asserts only that it equals itself.
  2. COVERAGE. Every money figure, comma-grouped integer and percentage in the
     decks' visible text, plus every headline `stat-num`/`big-number` value,
     must be accounted for by a check or listed in EXEMPT with a reason. So a
     NEW figure added to a deck fails this guard until it is either reproduced
     or excused. Without that half the guard silently stops covering the deck
     as the deck grows, which this repo rates worse than no guard at all.

ITS LIMITS, NAMED RATHER THAN DISCOVERED LATER:

  - **A bare small integer in prose is checked but NOT coverage-required.**
    "162 colleges across 39 states" and "3 of the 48" have explicit checks, and
    a new one like them would be missed by the sweep, because requiring every
    loose integer would drag in every year, step number and list count on the
    page. Money, thousands-separated counts, percentages and headline figures
    are the classes where a stale number is both most damaging and least
    visible, and those are required.
  - **Rounding is tolerated, drift is not.** A check accepts the exact figure,
    the nearest hundred, the nearest thousand and the $Nk/$N.NM forms, all
    derived from the computed value. So it cannot catch a deck that rounds
    badly; it is aimed at a figure from a different model era, which is off by
    tens of percent rather than by a hundred dollars.
  - **It says nothing about prose.** "It cuts both ways" beside a corrected
    count is this guard's blind spot; a count that moved from 13 to 3 changes
    what the sentence should say and only a person can see that.

IT SKIPS LOUDLY WHEN `presentation/` IS ABSENT and exits 0, which is every
clone and every CI run, and is the documented contract the three chart guards
already follow. Reporting OK over zero files would be worse than no check.
guards.yml discovers `check_*.py` dynamically, so this joined CI the day it was
committed and will skip there forever; it is a LOCAL guard in practice, and the
decks are a local artifact.

THE CALL SHAPE MATTERS, and getting it wrong is how the audit first produced a
$749,600 premium for a radiologic technologist. `enrollment_years` is
`pre_earnings_years(title, program_years)`, NOT `program_years` -- they differ
for every occupation carrying a training overlay -- and `working_years` is 0
unless the path is the part-time community-college one.
"""
